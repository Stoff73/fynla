          <!-- Protection Comes First -->
          <div>
            <h2 class="guide-section__heading">Protection Comes First</h2>
            <p class="guide-section__body">Before you grow your wealth, make sure your family is protected if something goes wrong.</p>
            <ul class="guide-list">
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Life insurance:</strong> enough to clear the mortgage and replace your income for the years your children are dependent.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Income protection:</strong> replaces your income if you can&rsquo;t work through illness or injury &mdash; the most underrated insurance.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Critical illness cover:</strong> pays a lump sum on diagnosis of a specified condition.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Employer death-in-service:</strong> check what you have &mdash; it&rsquo;s usually 2&ndash;4 times salary.</span></li>
            </ul>
          </div>

          <!-- The Protection Gap -->
          <div>
            <h2 class="guide-section__heading">The Protection Gap</h2>
            <p class="guide-section__body">Most families are underinsured. The gap between what you need and what you have is your protection gap.</p>
            <ul class="guide-list">
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>What does your family need per year?</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>For how many years?</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>What cover do you already have?</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>The difference is the gap you need to fill.</span></li>
            </ul>
          </div>

          <!-- Getting Started with Investing -->
          <div>
            <h2 class="guide-section__heading">Getting Started with Investing</h2>
            <p class="guide-section__body">Investing is how you grow your wealth over the long term. You don&rsquo;t need to be an expert to start.</p>
            <ul class="guide-list">
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Time in the market beats timing the market.</strong></span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Start with a low-cost global index fund if unsure.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Understand your risk profile: how long until you need the money? Can you stomach a 30% drop?</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Use an ISA wrapper for tax-free growth.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Don&rsquo;t invest money you will need within 5 years.</span></li>
            </ul>
          </div>

          <!-- Joint Financial Planning -->
          <div>
            <h2 class="guide-section__heading">Joint Financial Planning</h2>
            <p class="guide-section__body">If you are managing money as a couple, you need the full household picture.</p>
            <ul class="guide-list">
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Combine net worth views &mdash; you need to see both sides.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Both partners should know where everything is &mdash; In Case of Emergency letters help.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Consider: who is more vulnerable if the other dies? Plan for that scenario.</span></li>
            </ul>
          </div>

          <!-- Pension Housekeeping -->
          <div>
            <h2 class="guide-section__heading">Pension Housekeeping</h2>
            <p class="guide-section__body">If you have changed jobs a few times, you likely have pension pots scattered around. Time for a tidy-up.</p>
            <ul class="guide-list">
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Consolidate old workplace pensions &mdash; but check for guaranteed benefits first.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Make sure both partners are building adequate retirement provision.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Consider the pension impact of career breaks &mdash; common for parents.</span></li>
            </ul>
          </div>

