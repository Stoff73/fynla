              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>You want to ensure your family is provided for.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>You&rsquo;re thinking about gifting or trust strategies.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>You want your affairs in order.</span></li>
            </ul>
          </div>

          <!-- Understanding Your Estate -->
          <div>
            <h2 class="guide-section__heading">Understanding Your Estate</h2>
            <p class="guide-section__body">Your estate is everything you own at death: property, pensions (from April 2027), savings, investments, life insurance (unless in trust), and personal possessions &mdash; minus debts and funeral costs.</p>
            <p class="guide-section__body guide-section__body--spaced">If the total is above &pound;325,000 (the nil rate band), Inheritance Tax is charged at <strong>40% on the excess</strong>.</p>
          </div>

          <!-- The Allowances -->
          <div>
            <h2 class="guide-section__heading">The Allowances</h2>
            <p class="guide-section__body">Understanding the allowances is the foundation of estate planning.</p>
            <ul class="guide-list">
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Nil rate band:</strong> &pound;325,000 per person.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Residence nil rate band:</strong> &pound;175,000 (if passing your home to direct descendants).</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Both are transferable between spouses.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Maximum tax-free amount for a couple: &pound;1,000,000.</strong></span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>But: the residence nil rate band tapers for estates over &pound;2 million.</span></li>
            </ul>
          </div>

          <!-- Gifting Strategies -->
          <div>
            <h2 class="guide-section__heading">Gifting Strategies</h2>
            <p class="guide-section__body">Gifting is one of the most effective ways to reduce your estate &mdash; but you need to know the rules.</p>
            <ul class="guide-list">
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Annual exemption:</strong> &pound;3,000 per year (can carry forward one year).</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Small gifts:</strong> &pound;250 per person per year.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Wedding/civil partnership gifts:</strong> &pound;5,000 from parents, &pound;2,500 from grandparents.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Gifts from surplus income:</strong> unlimited, but must be regular and from income (not capital).</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>The 7-year rule:</strong> gifts over the annual exemption become tax-free if you survive 7 years.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Taper relief:</strong> reduces the tax if you die between 3&ndash;7 years after gifting.</span></li>
            </ul>
          </div>

          <!-- The April 2027 Pension Change -->
          <div>
            <h2 class="guide-section__heading">The April 2027 Pension Change</h2>
            <p class="guide-section__body">From April 2027, unused pension pots will be included in your estate for Inheritance Tax purposes. This is a significant change that affects many families.</p>
            <ul class="guide-list">
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Consider drawing down faster.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Gift from other assets instead.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Review your overall estate strategy.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Model both scenarios (current rules and 2027 rules) to understand the impact.</span></li>
            </ul>
          </div>

          <!-- Getting Your Documents in Order -->
          <div>
            <h2 class="guide-section__heading">Getting Your Documents in Order</h2>
            <p class="guide-section__body">Estate planning is not just about money. The paperwork matters too.</p>
            <ul class="guide-list">
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Will:</strong> essential &mdash; review every 3&ndash;5 years.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Lasting Power of Attorney:</strong> for finances and health decisions.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>In Case of Emergency letter:</strong> tells your family where everything is and what to do.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Life insurance:</strong> ensure policies are written in trust (otherwise they form part of your estate).</span></li>
            </ul>
          </div>

          <!-- Working with Professionals -->
          <div>
            <h2 class="guide-section__heading">Working with Professionals</h2>
            <p class="guide-section__body">For complex estates &mdash; trusts, business assets, cross-border situations &mdash; work with a solicitor and/or financial adviser. Fynla gives you the numbers to make those conversations productive and efficient.</p>
          </div>

