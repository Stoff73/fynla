            <h2 class="guide-intro-box__heading">This Guide is For You If&hellip;</h2>
            <ul class="guide-list" aria-label="Who this guide is for">
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>You&rsquo;re retired or approaching retirement.</span></li>
