          <!-- Getting on the Property Ladder -->
          <div>
            <h2 class="guide-section__heading">Getting on the Property Ladder</h2>
            <p class="guide-section__body">Buying your first home is one of the biggest financial steps you will take. Getting the basics right makes a real difference.</p>
            <ul class="guide-list">
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Save into a <strong>Lifetime ISA</strong> for the 25% government bonus (maximum &pound;4,000 per year, property up to &pound;450,000).</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Understand mortgage affordability &mdash; lenders typically offer 4&ndash;4.5 times your income.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Budget for stamp duty, solicitor fees, and surveys &mdash; add 3&ndash;5% to the purchase price.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Don&rsquo;t drain your emergency fund for a deposit.</span></li>
            </ul>
          </div>

          <!-- ISA Strategy -->
          <div>
            <h2 class="guide-section__heading">ISA Strategy</h2>
            <p class="guide-section__body">ISAs are your most powerful tax-free savings and investment tool. Use them in order of priority.</p>
            <ul class="guide-list">
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Max the <strong>Lifetime ISA first</strong> (&pound;4,000 for your house deposit).</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Remaining allowance: <strong>Cash ISA</strong> for short-term goals, <strong>Stocks and Shares ISA</strong> for goals 5+ years away.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Couples: &pound;40,000 combined ISA allowance per year.</span></li>
            </ul>
          </div>

          <!-- Pension Check -->
          <div>
            <h2 class="guide-section__heading">Pension Check</h2>
            <p class="guide-section__body">Your workplace pension is one of the best benefits you have. Make sure you are getting the most from it.</p>
            <ul class="guide-list">
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Are you getting the <strong>full employer match</strong>? If your employer matches up to 5%, contribute at least 5%.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Consider <strong>salary sacrifice</strong> if your employer offers it &mdash; you save on National Insurance too.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Check the charges on your workplace pension fund.</span></li>
            </ul>
          </div>

          <!-- Debt Strategy -->
          <div>
            <h2 class="guide-section__heading">Debt Strategy</h2>
            <p class="guide-section__body">Not all debt is equal. Prioritise the expensive stuff and be strategic about the rest.</p>
            <ul class="guide-list">
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Pay off high-interest debt first</strong> &mdash; credit cards, overdrafts.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Student loan:</strong> don&rsquo;t overpay &mdash; it&rsquo;s written off eventually.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Mortgage:</strong> overpay if your rate is above savings rates.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Keep a minimum of <strong>3 months&rsquo; expenses</strong> as an emergency fund.</span></li>
            </ul>
          </div>

          <!-- Tracking Progress -->
          <div>
            <h2 class="guide-section__heading">Tracking Progress</h2>
            <p class="guide-section__body">Your <strong>net worth</strong> is the single best measure of your financial progress. Calculate it: assets minus liabilities.</p>
            <p class="guide-step__body">Track it monthly or quarterly. It should trend upwards &mdash; even slowly. That upward trend is proof that what you are doing is working.</p>
          </div>

