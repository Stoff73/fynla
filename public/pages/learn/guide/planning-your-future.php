      <div class="guide-content__inner">
        <div class="guide-content__card">

          <!-- Intro box -->
          <div class="guide-intro-box">
            <h2 class="guide-intro-box__heading">This Guide is For You If&hellip;</h2>
            <ul class="guide-list" aria-label="Who this guide is for">
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Retirement is 5&ndash;20 years away.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>You have multiple pension pots from different employers.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>You&rsquo;re wondering if early retirement is realistic.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>You want to make the most of your peak earning years.</span></li>
            </ul>
          </div>

          <!-- Step 1 -->
          <div>
            <div class="guide-step__header">
              <span class="guide-step__number" aria-hidden="true">1</span>
              <h2 class="guide-step__heading">Gather Everything</h2>
            </div>
            <p class="guide-step__body">You cannot plan what you cannot see. Start by getting a complete picture of where you stand.</p>
            <ul class="guide-list">
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>List every pension: workplace (current and old), personal, Self-Invested Personal Pension.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Get valuations from each provider.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Check your State Pension forecast at gov.uk.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Add ISAs, investments, and property equity.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Calculate your total retirement pot.</span></li>
            </ul>
          </div>

          <!-- Step 2 -->
          <div>
            <div class="guide-step__header">
              <span class="guide-step__number" aria-hidden="true">2</span>
              <h2 class="guide-step__heading">Define Your Income Need</h2>
            </div>
            <p class="guide-step__body">What will you actually spend in retirement? Be honest. The Pension and Lifetime Savings Association benchmarks are a useful starting point.</p>
            <ul class="guide-list">
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Essential costs:</strong> housing, food, bills, insurance.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Lifestyle costs:</strong> holidays, hobbies, eating out.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>One-off costs:</strong> home repairs, car replacement.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Later-life costs:</strong> care, mobility.</span></li>
            </ul>
          </div>

          <!-- Step 3 -->
          <div>
            <div class="guide-step__header">
              <span class="guide-step__number" aria-hidden="true">3</span>
              <h2 class="guide-step__heading">Model Your Retirement Date</h2>
            </div>
            <p class="guide-step__body">Take your total pot, add the State Pension and any Defined Benefit pensions. Model whether this can sustain your spending from your target retirement age to age 90&ndash;95.</p>
            <p class="guide-step__body">Don&rsquo;t forget inflation &mdash; &pound;30,000 today is very different from &pound;30,000 in 20 years.</p>
          </div>

          <!-- Step 4 -->
          <div>
            <div class="guide-step__header">
              <span class="guide-step__number" aria-hidden="true">4</span>
              <h2 class="guide-step__heading">Stress-Test with Monte Carlo</h2>
            </div>
            <p class="guide-step__body">A single projection assumes average returns every year. Real markets don&rsquo;t work that way.</p>
            <p class="guide-step__body">Monte Carlo simulations test thousands of scenarios &mdash; good markets, bad markets, crashes early in retirement. Aim for <strong>80%+ probability of success</strong>.</p>
          </div>

          <!-- Step 5 -->
          <div>
            <div class="guide-step__header">
              <span class="guide-step__number" aria-hidden="true">5</span>
              <h2 class="guide-step__heading">Pull the Levers</h2>
            </div>
            <p class="guide-step__body">If the numbers don&rsquo;t work yet, you have options.</p>
            <ul class="guide-list">
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Increase contributions</strong> &mdash; even 2% more has a big impact over time.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Delay retirement by 1&ndash;3 years</strong> &mdash; a huge double benefit (more saving, less drawdown).</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span><strong>Plan a phased retirement</strong> &mdash; part-time work bridging the gap.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Reduce target spending.</span></li>
              <li class="guide-list__item"><span class="guide-list__bullet" aria-hidden="true"></span><span>Consider downsizing.</span></li>
            </ul>
          </div>

          <!-- Step 6 -->
          <div>
            <div class="guide-step__header">
              <span class="guide-step__number" aria-hidden="true">6</span>
              <h2 class="guide-step__heading">Review Annually</h2>
            </div>
            <p class="guide-step__body">Your retirement date isn&rsquo;t fixed &mdash; it moves as markets, contributions, and plans change. Check in yearly. Adjust as needed. The earlier you spot a problem, the easier it is to fix.</p>
          </div>

        </div>
      </div>
