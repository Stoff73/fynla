          <!-- The Short Answer -->
          <div class="article-section">
            <div class="article-highlight">
              <h2 class="article-highlight__heading">The Short Answer</h2>
              <p class="article-highlight__text">
                Salary sacrifice (sometimes called salary exchange) is an arrangement where you give up part of your salary
                in exchange for a larger employer pension contribution. You pay less income tax and National Insurance.
                Your employer pays less National Insurance too &mdash; and good employers pass that saving into your pension.
              </p>
            </div>
          </div>

          <!-- How It Works -->
          <div class="article-section">
            <h2 class="article-heading">How It Works</h2>
            <p class="article-body-text" style="margin-bottom:0.75rem;">
              Here is an example. You earn &pound;50,000. You sacrifice &pound;5,000 of salary. Your gross pay drops to
              &pound;45,000. But your employer puts the full &pound;5,000 (plus their National Insurance saving) into your
              pension. You save 20&ndash;40% income tax plus 12% National Insurance on the sacrificed amount.
            </p>
            <div class="salary-compare-box">
              <div class="salary-compare-grid">
                <div>
                  <p class="salary-compare-col__label">Without salary sacrifice</p>
                  <ul class="salary-compare-list" aria-label="Without salary sacrifice">
                    <li class="salary-compare-list__item">Gross salary: &pound;50,000</li>
                    <li class="salary-compare-list__item">You contribute &pound;5,000 from net pay</li>
                    <li class="salary-compare-list__item">You still pay National Insurance on &pound;50,000</li>
                  </ul>
                </div>
                <div>
                  <p class="salary-compare-col__label salary-compare-col__label--positive">With salary sacrifice</p>
                  <ul class="salary-compare-list" aria-label="With salary sacrifice">
                    <li class="salary-compare-list__item">Gross salary: &pound;45,000</li>
                    <li class="salary-compare-list__item">Employer contributes &pound;5,000+ to pension</li>
                    <li class="salary-compare-list__item">You pay National Insurance on &pound;45,000 only</li>
                  </ul>
                </div>
              </div>
            </div>
          </div>

          <!-- The Benefits -->
          <div class="article-section">
            <h2 class="article-heading">The Benefits</h2>
            <ul class="article-list" aria-label="Benefits of salary sacrifice">
              <li class="article-list__item">
                <span class="article-list__dot article-list__dot--spring" aria-hidden="true"></span>
                <span><strong>More goes into your pension</strong> for the same cost to you.</span>
              </li>
              <li class="article-list__item">
                <span class="article-list__dot article-list__dot--spring" aria-hidden="true"></span>
                <span><strong>Lower National Insurance contributions</strong> for you and your employer.</span>
              </li>
              <li class="article-list__item">
                <span class="article-list__dot article-list__dot--spring" aria-hidden="true"></span>
                <span><strong>Reduces your taxable income</strong> &mdash; helpful near tax band boundaries.</span>
              </li>
              <li class="article-list__item">
                <span class="article-list__dot article-list__dot--spring" aria-hidden="true"></span>
                <span><strong>Especially powerful for higher-rate taxpayers</strong> who save 40% income tax plus National Insurance.</span>
              </li>
            </ul>
          </div>

          <!-- The Risks -->
          <div class="article-section">
            <h2 class="article-heading">The Risks</h2>
            <p class="article-body-text" style="margin-bottom:0.75rem;">A lower gross salary could affect:</p>
            <ul class="article-list" aria-label="Risks of salary sacrifice">
              <li class="article-list__item">
                <span class="article-list__dot article-list__dot--raspberry" aria-hidden="true"></span>
                <span><strong>Mortgage applications</strong> &mdash; lenders use gross salary to assess affordability.</span>
              </li>
              <li class="article-list__item">
                <span class="article-list__dot article-list__dot--raspberry" aria-hidden="true"></span>
                <span><strong>Statutory sick pay</strong> and <strong>maternity or paternity pay</strong> &mdash; both based on gross earnings.</span>
              </li>
              <li class="article-list__item">
                <span class="article-list__dot article-list__dot--raspberry" aria-hidden="true"></span>
                <span><strong>Life insurance</strong> &mdash; if your employer scheme is based on salary.</span>
              </li>
              <li class="article-list__item">
                <span class="article-list__dot article-list__dot--raspberry" aria-hidden="true"></span>
                <span><strong>No guarantee of employer savings</strong> &mdash; your employer is not obligated to pass on their National Insurance saving.</span>
              </li>
            </ul>
          </div>

          <!-- Who Should Consider It? -->
          <div class="article-section">
            <h2 class="article-heading">Who Should Consider It?</h2>
            <ul class="article-list" aria-label="Who benefits most from salary sacrifice">
              <li class="article-list__item">
                <span class="article-list__dot article-list__dot--violet" aria-hidden="true"></span>
                <span>Higher and additional rate taxpayers get the biggest benefit.</span>
              </li>
              <li class="article-list__item">
                <span class="article-list__dot article-list__dot--violet" aria-hidden="true"></span>
                <span>Anyone whose employer passes on the National Insurance saving.</span>
              </li>
              <li class="article-list__item">
                <span class="article-list__dot article-list__dot--violet" aria-hidden="true"></span>
                <span>People not planning to apply for a mortgage soon.</span>
              </li>
            </ul>
