          <!-- Before 5 April -->
          <div class="guide-section">
            <h2 class="guide-section__heading">Before 5 April 2026</h2>

            <div class="checklist-item">
              <div class="checklist-item__row">
                <span class="checklist-item__checkbox checklist-item__checkbox--spring" role="presentation" aria-hidden="true"></span>
                <div>
                  <p class="checklist-item__title">Use your ISA allowance</p>
                  <p class="checklist-item__body">You can contribute up to &pound;20,000 across all ISA types. Unused allowance does not carry forward.</p>
                </div>
              </div>
            </div>

            <div class="checklist-item">
              <div class="checklist-item__row">
                <span class="checklist-item__checkbox checklist-item__checkbox--spring" role="presentation" aria-hidden="true"></span>
                <div>
                  <p class="checklist-item__title">Use your pension annual allowance</p>
                  <p class="checklist-item__body">Up to &pound;60,000 in pension contributions (including employer contributions and tax relief). Check if you have carry forward from the previous three years.</p>
                </div>
              </div>
            </div>

            <div class="checklist-item">
              <div class="checklist-item__row">
                <span class="checklist-item__checkbox checklist-item__checkbox--spring" role="presentation" aria-hidden="true"></span>
                <div>
                  <p class="checklist-item__title">Use your annual gift exemptions</p>
                  <p class="checklist-item__body">&pound;3,000 annual exemption (can carry forward one year if unused). Plus &pound;250 small gifts to any number of individuals.</p>
                </div>
              </div>
            </div>

            <div class="checklist-item">
              <div class="checklist-item__row">
                <span class="checklist-item__checkbox checklist-item__checkbox--spring" role="presentation" aria-hidden="true"></span>
                <div>
                  <p class="checklist-item__title">Use your Capital Gains Tax annual exempt amount</p>
                  <p class="checklist-item__body">&pound;3,000 of gains are tax-free. Consider selling and rebuying assets (known as bed and ISA) to crystallise gains within the allowance.</p>
                </div>
              </div>
            </div>

            <div class="checklist-item">
              <div class="checklist-item__row">
                <span class="checklist-item__checkbox checklist-item__checkbox--spring" role="presentation" aria-hidden="true"></span>
                <div>
                  <p class="checklist-item__title">Review salary sacrifice</p>
                  <p class="checklist-item__body">Salary sacrifice pension contributions save both income tax and National Insurance. Check if your employer offers it.</p>
                </div>
              </div>
            </div>

            <div class="checklist-item">
              <div class="checklist-item__row">
                <span class="checklist-item__checkbox checklist-item__checkbox--spring" role="presentation" aria-hidden="true"></span>
                <div>
                  <p class="checklist-item__title">Check marriage allowance eligibility</p>
                  <p class="checklist-item__body">If one partner earns below the personal allowance (&pound;12,570), they can transfer &pound;1,260 to the other &mdash; saving up to &pound;252 per year.</p>
                </div>
              </div>
            </div>

            <div class="checklist-item">
              <div class="checklist-item__row">
                <span class="checklist-item__checkbox checklist-item__checkbox--spring" role="presentation" aria-hidden="true"></span>
                <div>
                  <p class="checklist-item__title">File self-assessment if needed</p>
                  <p class="checklist-item__body">The deadline for online self-assessment for 2024/25 is 31 January 2026. Don&rsquo;t leave it until the last minute.</p>
                </div>
              </div>
            </div>
          </div>

