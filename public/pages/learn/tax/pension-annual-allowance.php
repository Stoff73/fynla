      <div class="guide-article__inner">
        <article class="guide-article__card">

          <!-- The Standard Allowance -->
          <div class="guide-highlight">
            <h2>The Standard Allowance</h2>
            <p>
              The pension annual allowance for 2026/27 is <strong>&pound;60,000</strong>. This is the maximum you can
              contribute to all your pensions in a single tax year while still receiving tax relief. It includes your
              personal contributions, employer contributions, and any tax relief added by HMRC.
            </p>
          </div>

          <!-- Carry Forward -->
          <div class="guide-section">
            <h2 class="guide-section__heading">Carry Forward</h2>
            <p class="guide-section__body">
              If you did not use your full allowance in the previous three tax years, you can carry the unused amount
              forward. This means you could potentially contribute well above &pound;60,000 in a single year.
            </p>
            <ul class="guide-bullet-list" aria-label="Carry forward rules">
              <li class="guide-bullet-list__item">
                <span class="guide-bullet-list__dot guide-bullet-list__dot--spring" aria-hidden="true"></span>
                <span>You must have been a member of a registered pension scheme in each carry forward year.</span>
              </li>
              <li class="guide-bullet-list__item">
                <span class="guide-bullet-list__dot guide-bullet-list__dot--spring" aria-hidden="true"></span>
                <span>Use the oldest year&rsquo;s unused allowance first.</span>
              </li>
              <li class="guide-bullet-list__item">
                <span class="guide-bullet-list__dot guide-bullet-list__dot--spring" aria-hidden="true"></span>
                <span>You must use the current year&rsquo;s &pound;60,000 allowance before dipping into carry forward.</span>
              </li>
            </ul>
          </div>

          <!-- Tapered Annual Allowance -->
          <div class="guide-section">
            <h2 class="guide-section__heading">Tapered Annual Allowance</h2>
            <p class="guide-section__body">
              If your adjusted income exceeds <strong>&pound;260,000</strong>, your annual allowance is reduced by
              &pound;1 for every &pound;2 over that threshold. The minimum tapered allowance is
              <strong>&pound;10,000</strong>.
            </p>
            <div class="guide-table-wrap">
              <table class="guide-table" aria-label="Tapered annual allowance by adjusted income">
                <thead>
                  <tr>
                    <th scope="col">Adjusted Income</th>
                    <th scope="col">Annual Allowance</th>
                  </tr>
                </thead>
                <tbody>
                  <tr>
                    <td>Up to &pound;260,000</td>
                    <td>&pound;60,000</td>
                  </tr>
                  <tr>
                    <td>&pound;300,000</td>
                    <td>&pound;40,000</td>
                  </tr>
                  <tr>
                    <td>&pound;360,000 or above</td>
                    <td>&pound;10,000</td>
                  </tr>
                </tbody>
              </table>
            </div>
            <p class="guide-caption">The taper only applies if your threshold income also exceeds &pound;200,000.</p>
          </div>

          <!-- Money Purchase Annual Allowance -->
          <div class="guide-section">
            <h2 class="guide-section__heading">Money Purchase Annual Allowance</h2>
            <p class="guide-section__body">
              If you have flexibly accessed your defined contribution pension (for example, through flexi-access
              drawdown or taking an uncrystallised funds pension lump sum), your allowance for further money purchase
              contributions drops to <strong>&pound;10,000</strong>. This is the Money Purchase Annual Allowance.
            </p>
            <ul class="guide-bullet-list" aria-label="Money Purchase Annual Allowance rules">
              <li class="guide-bullet-list__item">
                <span class="guide-bullet-list__dot guide-bullet-list__dot--violet" aria-hidden="true"></span>
                <span>Taking your 25% tax-free lump sum alone does not trigger the Money Purchase Annual Allowance.</span>
              </li>
              <li class="guide-bullet-list__item">
                <span class="guide-bullet-list__dot guide-bullet-list__dot--violet" aria-hidden="true"></span>
                <span>Carry forward cannot be used for the Money Purchase Annual Allowance &mdash; it is a hard &pound;10,000 limit.</span>
              </li>
              <li class="guide-bullet-list__item">
                <span class="guide-bullet-list__dot guide-bullet-list__dot--violet" aria-hidden="true"></span>
                <span>Once triggered, the Money Purchase Annual Allowance applies for the rest of your life.</span>
              </li>
            </ul>
          </div>

          <!-- What Happens If You Exceed -->
          <div class="guide-section">
            <h2 class="guide-section__heading">What Happens If You Exceed the Allowance</h2>
            <p class="guide-section__body">
              Contributions above your annual allowance are subject to an annual allowance charge. The excess is added
              to your income for the year and taxed at your marginal rate. If the charge exceeds &pound;2,000, you
              can ask your pension scheme to pay it from your pension pot (known as scheme pays).
            </p>
          </div>

