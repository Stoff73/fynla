            </div>
          </div>

          <!-- Key Rules -->
          <div class="guide-section">
            <h2 class="guide-section__heading">Key Rules</h2>
            <ul class="guide-bullet-list" aria-label="ISA key rules">
              <li class="guide-bullet-list__item">
                <span class="guide-bullet-list__dot guide-bullet-list__dot--spring" aria-hidden="true"></span>
                <span>You can hold one of each ISA type per tax year.</span>
              </li>
              <li class="guide-bullet-list__item">
                <span class="guide-bullet-list__dot guide-bullet-list__dot--spring" aria-hidden="true"></span>
                <span>Unused allowance does not carry forward to the next tax year.</span>
              </li>
              <li class="guide-bullet-list__item">
                <span class="guide-bullet-list__dot guide-bullet-list__dot--spring" aria-hidden="true"></span>
                <span>ISAs are individual &mdash; there is no joint ISA. Couples each get &pound;20,000.</span>
              </li>
              <li class="guide-bullet-list__item">
                <span class="guide-bullet-list__dot guide-bullet-list__dot--spring" aria-hidden="true"></span>
                <span>You must be a UK resident and aged 18 or over (16 for Cash ISAs).</span>
              </li>
            </ul>
          </div>

          <!-- Transferring ISAs -->
          <div class="guide-section">
            <h2 class="guide-section__heading">Transferring ISAs</h2>
            <p class="guide-section__body">
              You can transfer ISAs between providers without losing your tax-free status. Current year contributions
              must be transferred in full; previous years&rsquo; contributions can be transferred partially.
            </p>
            <p class="guide-caption">Always use the formal ISA transfer process &mdash; withdrawing and redepositing uses up your annual allowance.</p>
          </div>

          <!-- Flexible ISAs -->
          <div class="guide-section">
            <h2 class="guide-section__heading">Flexible ISAs</h2>
            <p class="guide-section__body">
              Some providers offer flexible ISAs. If you withdraw money, you can replace it within the same tax year
              without it counting towards your annual allowance. Not all providers offer this, so check before withdrawing.
            </p>
          </div>

