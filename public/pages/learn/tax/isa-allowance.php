        <article class="guide-article__card">

          <!-- The Annual Allowance -->
          <div class="guide-highlight">
            <h2>The Annual Allowance</h2>
            <p>
              The ISA allowance is <strong>&pound;20,000</strong> per tax year (6 April to 5 April). You can split
              this across different ISA types, but the total must not exceed &pound;20,000. The allowance does not
              carry forward &mdash; if you don&rsquo;t use it, you lose it.
            </p>
          </div>

          <!-- Types of ISA -->
          <div class="guide-section">
            <h2 class="guide-section__heading">Types of ISA</h2>
            <div class="guide-isa-types">
              <div class="guide-highlight guide-highlight--stacked">
                <p class="guide-isa-type__name">Cash ISA</p>
                <p class="guide-isa-type__desc">Tax-free savings account. Interest earned is free from income tax. You can hold one Cash ISA per tax year (multiple from different years).</p>
              </div>
              <div class="guide-highlight guide-highlight--stacked">
                <p class="guide-isa-type__name">Stocks and Shares ISA</p>
                <p class="guide-isa-type__desc">Invest in funds, shares, and bonds with no Capital Gains Tax or income tax on returns. Best suited for goals five or more years away.</p>
              </div>
              <div class="guide-highlight guide-highlight--stacked">
                <p class="guide-isa-type__name">Lifetime ISA</p>
                <p class="guide-isa-type__desc">For 18&ndash;39 year olds saving for a first home or retirement. &pound;4,000 annual sub-limit (counts towards &pound;20,000 total). 25% government bonus on contributions &mdash; up to &pound;1,000 per year. 25% penalty on withdrawals for other purposes.</p>
              </div>
              <div class="guide-highlight guide-highlight--stacked guide-highlight--last">
                <p class="guide-isa-type__name">Innovative Finance ISA</p>
                <p class="guide-isa-type__desc">Holds peer-to-peer lending investments. Interest and gains are tax-free, but the underlying investments carry higher risk.</p>
              </div>
            </div>
          </div>

          <!-- Limits Table -->
          <div class="guide-section">
            <h2 class="guide-section__heading">Limits at a Glance</h2>
            <div class="guide-table-wrap">
              <table class="guide-table" aria-label="ISA annual subscription limits">
