          <!-- What is CGT -->
          <div class="guide-highlight">
            <h2>What is Capital Gains Tax?</h2>
            <p>
              Capital Gains Tax is charged on the profit you make when you sell or dispose of an asset that has
              increased in value. You only pay tax on the gain &mdash; not the full sale price. Everyone gets an
              annual exempt amount before tax is due.
            </p>
          </div>

          <!-- Annual Exempt Amount -->
          <div class="guide-section">
            <h2 class="guide-section__heading">Annual Exempt Amount</h2>
            <p class="guide-section__body">
              The annual exempt amount for 2026/27 is <strong>&pound;3,000</strong>. This was reduced from
              &pound;6,000 in 2023/24 and &pound;12,300 in 2022/23. Gains below this threshold are tax-free.
            </p>
            <p class="guide-caption">The annual exempt amount cannot be carried forward &mdash; use it or lose it each tax year.</p>
          </div>

          <!-- Tax Rates -->
          <div class="guide-section">
            <h2 class="guide-section__heading">Tax Rates</h2>
            <div class="guide-table-wrap">
              <table class="guide-table" aria-label="Capital Gains Tax rates by asset type and income band">
                <thead>
                  <tr>
                    <th scope="col">Asset Type</th>
                    <th scope="col">Basic Rate</th>
                    <th scope="col">Higher Rate</th>
                  </tr>
                </thead>
                <tbody>
                  <tr>
                    <td>Most assets (shares, funds, etc.)</td>
                    <td>10%</td>
                    <td>20%</td>
                  </tr>
                  <tr>
                    <td>Residential property</td>
                    <td>18%</td>
                    <td>24%</td>
                  </tr>
                </tbody>
              </table>
            </div>
            <p class="guide-caption">
              Which rate you pay depends on your total taxable income plus the gain. If the gain pushes you into the
              higher rate band, the portion above the threshold is taxed at the higher rate.
            </p>
          </div>

          <!-- Tax-Free Wrappers -->
          <div class="guide-section">
            <h2 class="guide-section__heading">Tax-Free Wrappers</h2>
            <ul class="guide-bullet-list" aria-label="Tax-free wrappers for Capital Gains Tax">
              <li class="guide-bullet-list__item">
                <span class="guide-bullet-list__dot guide-bullet-list__dot--spring" aria-hidden="true"></span>
                <span><strong>ISAs:</strong> gains within an ISA are completely exempt from Capital Gains Tax.</span>
              </li>
              <li class="guide-bullet-list__item">
                <span class="guide-bullet-list__dot guide-bullet-list__dot--spring" aria-hidden="true"></span>
                <span><strong>Pensions:</strong> gains within pension wrappers are tax-free.</span>
              </li>
              <li class="guide-bullet-list__item">
                <span class="guide-bullet-list__dot guide-bullet-list__dot--spring" aria-hidden="true"></span>
                <span><strong>Main residence:</strong> your primary home is usually exempt under Private Residence Relief.</span>
              </li>
            </ul>
          </div>

          <!-- Ways to Reduce -->
          <div class="guide-section">
            <h2 class="guide-section__heading">Ways to Reduce Your Bill</h2>
            <ul class="guide-bullet-list" aria-label="Strategies to reduce Capital Gains Tax">
              <li class="guide-bullet-list__item">
                <span class="guide-bullet-list__dot guide-bullet-list__dot--violet" aria-hidden="true"></span>
                <span><strong>Use your annual exempt amount</strong> &mdash; sell assets each year to crystallise gains within the &pound;3,000 allowance.</span>
              </li>
              <li class="guide-bullet-list__item">
                <span class="guide-bullet-list__dot guide-bullet-list__dot--violet" aria-hidden="true"></span>
                <span><strong>Offset losses</strong> &mdash; capital losses can be set against gains in the same or future tax years.</span>
              </li>
              <li class="guide-bullet-list__item">
                <span class="guide-bullet-list__dot guide-bullet-list__dot--violet" aria-hidden="true"></span>
                <span><strong>Transfer to your spouse</strong> &mdash; transfers between spouses are at no gain/no loss, giving you two annual exempt amounts.</span>
              </li>
              <li class="guide-bullet-list__item">
                <span class="guide-bullet-list__dot guide-bullet-list__dot--violet" aria-hidden="true"></span>
                <span><strong>Hold assets in ISAs</strong> &mdash; moving investments into ISA wrappers shelters future gains.</span>
              </li>
            </ul>
          </div>

