        <article class="article-card">

          <!-- The Short Answer -->
          <div class="article-section">
            <div class="article-highlight">
              <h2 class="article-highlight__heading">The Short Answer</h2>
              <p class="article-highlight__text">
                An Individual Savings Account (ISA) is a tax-free wrapper for your savings or investments. You can save up to
                <strong>&pound;20,000 per tax year</strong> and pay no tax on the interest or investment returns.
              </p>
            </div>
          </div>

          <!-- Types of ISA -->
          <div class="article-section">
            <h2 class="article-heading">Types of ISA</h2>
            <div class="article-isa-grid">
              <div class="article-isa-col">
                <p class="article-isa-col__name">Cash ISA</p>
                <p class="article-isa-col__desc">A savings account where the interest is tax-free. Best for short-term goals or your emergency fund.</p>
              </div>
              <div class="article-isa-col">
                <p class="article-isa-col__name">Stocks and Shares ISA</p>
                <p class="article-isa-col__desc">Invest in funds, shares, or bonds with no tax on gains or dividends. Better for longer-term goals (5+ years).</p>
              </div>
              <div class="article-isa-col">
                <p class="article-isa-col__name">Lifetime ISA</p>
                <p class="article-isa-col__desc">For under-40s saving for a first home or retirement. The government adds a 25% bonus on up to &pound;4,000 per year.</p>
              </div>
              <div class="article-isa-col">
                <p class="article-isa-col__name">Innovative Finance ISA</p>
                <p class="article-isa-col__desc">Holds peer-to-peer loans. Higher potential returns but higher risk than cash.</p>
              </div>
            </div>
          </div>

          <!-- ISA Allowance -->
          <div class="article-section">
            <h2 class="article-heading">ISA Allowance 2026/27</h2>
            <ul class="article-list" aria-label="ISA allowance key points">
              <li class="article-list__item">
                <span class="article-list__dot article-list__dot--spring" aria-hidden="true"></span>
                <span><strong>&pound;20,000</strong> total across all ISAs per tax year.</span>
              </li>
              <li class="article-list__item">
                <span class="article-list__dot article-list__dot--spring" aria-hidden="true"></span>
                <span>You can split the allowance between different ISA types.</span>
              </li>
              <li class="article-list__item">
                <span class="article-list__dot article-list__dot--spring" aria-hidden="true"></span>
                <span>Lifetime ISA has a <strong>&pound;4,000</strong> sub-limit within the &pound;20,000.</span>
              </li>
            </ul>
          </div>

          <!-- How ISAs Save You Tax -->
          <div class="article-section">
            <h2 class="article-heading">How ISAs Save You Tax</h2>
            <p class="article-body-text">
              Without an ISA, you would pay income tax on savings interest above your Personal Savings Allowance
              (&pound;1,000 for basic rate taxpayers, &pound;500 for higher rate). Inside an ISA, all interest and
              investment growth is completely tax-free &mdash; no income tax, no Capital Gains Tax, and no tax on dividends.
            </p>
          </div>

          <!-- ISA Tips -->
          <div class="article-section">
            <h2 class="article-heading">ISA Tips</h2>
            <ul class="article-list" aria-label="ISA tips">
              <li class="article-list__item">
                <span class="article-list__dot article-list__dot--violet" aria-hidden="true"></span>
                <span><strong>Use it or lose it.</strong> Your annual allowance does not roll over to the next tax year.</span>
              </li>
              <li class="article-list__item">
                <span class="article-list__dot article-list__dot--violet" aria-hidden="true"></span>
                <span><strong>Start early in the tax year.</strong> The sooner your money is sheltered, the more tax-free growth you capture.</span>
              </li>
              <li class="article-list__item">
                <span class="article-list__dot article-list__dot--violet" aria-hidden="true"></span>
                <span><strong>Consider Stocks and Shares</strong> for longer-term goals (5+ years) where you can ride out short-term volatility.</span>
              </li>
            </ul>
          </div>

