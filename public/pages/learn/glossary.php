    <section id="glossary" class="glossary-content" aria-labelledby="glossary-heading">
      <h2 id="glossary-heading" class="visually-hidden">Glossary terms A to Z</h2>
      <div class="glossary-content__inner">

        <!-- A -->
        <div id="letter-A" class="glossary-letter-group">
          <div class="glossary-letter-heading">
            <span class="glossary-letter-heading__text" aria-hidden="true">A</span>
          </div>
          <dl class="glossary-term-list">
            <div id="annuity" class="glossary-term" role="article">
              <dt class="glossary-term__name">Annuity</dt>
              <dd class="glossary-term__definition">An insurance product that converts your pension pot into a guaranteed income for life. Once purchased, the decision is irreversible. Rates vary depending on your age, health, and market conditions.</dd>
              <dd><a href="/learn/what-is-drawdown" class="glossary-term__link">Compare with drawdown</a></dd>
            </div>
            <div id="annual-allowance" class="glossary-term" role="article">
              <dt class="glossary-term__name">Annual Allowance</dt>
              <dd class="glossary-term__definition">The maximum amount you can contribute to pensions in a tax year while still receiving tax relief. Currently &pound;60,000 per year, though this is reduced for very high earners.</dd>
              <dd><a href="/features/pension-tracker" class="glossary-term__link">Track your pension contributions</a></dd>
            </div>
          </dl>
        </div>

        <!-- B -->
        <div id="letter-B" class="glossary-letter-group">
          <div class="glossary-letter-heading">
            <span class="glossary-letter-heading__text" aria-hidden="true">B</span>
          </div>
          <dl class="glossary-term-list">
            <div id="basic-rate" class="glossary-term" role="article">
              <dt class="glossary-term__name">Basic Rate</dt>
              <dd class="glossary-term__definition">The 20% income tax band that applies to taxable income between &pound;12,571 and &pound;50,270 (2026/27). Most UK taxpayers fall within this band.</dd>
            </div>
            <div id="beneficiary" class="glossary-term" role="article">
              <dt class="glossary-term__name">Beneficiary</dt>
              <dd class="glossary-term__definition">A person or organisation you nominate to receive a benefit, such as a pension pot or life insurance payout, after your death.</dd>
            </div>
          </dl>
        </div>

        <!-- C -->
        <div id="letter-C" class="glossary-letter-group">
          <div class="glossary-letter-heading">
            <span class="glossary-letter-heading__text" aria-hidden="true">C</span>
          </div>
          <dl class="glossary-term-list">
            <div id="capital-gains-tax" class="glossary-term" role="article">
              <dt class="glossary-term__name">Capital Gains Tax</dt>
              <dd class="glossary-term__definition">Tax on the profit you make when you sell an asset (such as a second property or shares) for more than you paid for it. There is an annual tax-free allowance, and rates depend on the asset type and your income tax band.</dd>
            </div>
            <div id="carry-forward" class="glossary-term" role="article">
              <dt class="glossary-term__name">Carry Forward</dt>
              <dd class="glossary-term__definition">A rule that lets you use any unused pension annual allowance from the previous three tax years, as long as you were a member of a pension scheme during those years.</dd>
            </div>
            <div id="cash-isa" class="glossary-term" role="article">
              <dt class="glossary-term__name">Cash ISA</dt>
              <dd class="glossary-term__definition">A savings account where the interest is completely tax-free. Best suited for short-term goals or emergency funds where you need easy access to your money.</dd>
              <dd><a href="/learn/what-is-an-isa" class="glossary-term__link">Learn about ISAs</a></dd>
            </div>
            <div id="critical-illness-cover" class="glossary-term" role="article">
              <dt class="glossary-term__name">Critical Illness Cover</dt>
              <dd class="glossary-term__definition">An insurance policy that pays out a tax-free lump sum if you are diagnosed with a specified serious illness, such as cancer, heart attack, or stroke.</dd>
            </div>
          </dl>
        </div>

        <!-- D -->
        <div id="letter-D" class="glossary-letter-group">
          <div class="glossary-letter-heading">
            <span class="glossary-letter-heading__text" aria-hidden="true">D</span>
          </div>
          <dl class="glossary-term-list">
            <div id="death-in-service" class="glossary-term" role="article">
              <dt class="glossary-term__name">Death in Service</dt>
              <dd class="glossary-term__definition">A workplace benefit that pays a lump sum (typically 2&ndash;4 times your salary) to your nominated beneficiaries if you die while employed. It is essentially free life insurance from your employer.</dd>
            </div>
            <div id="defined-benefit-pension" class="glossary-term" role="article">
              <dt class="glossary-term__name">Defined Benefit Pension</dt>
              <dd class="glossary-term__definition">A pension scheme that promises a specific annual income in retirement, usually based on your salary and years of service. Also known as a final salary or career average pension. These are increasingly rare in the private sector.</dd>
              <dd><a href="/features/pension-tracker" class="glossary-term__link">Track your pensions</a></dd>
            </div>
            <div id="defined-contribution-pension" class="glossary-term" role="article">
              <dt class="glossary-term__name">Defined Contribution Pension</dt>
              <dd class="glossary-term__definition">A pension where you and your employer contribute money into a pot that is invested. The amount you get in retirement depends on how much was contributed and how the investments performed. Most workplace pensions are this type.</dd>
              <dd><a href="/features/pension-tracker" class="glossary-term__link">Track your pensions</a></dd>
            </div>
            <div id="drawdown" class="glossary-term" role="article">
              <dt class="glossary-term__name">Drawdown</dt>
              <dd class="glossary-term__definition">A way of taking income from your Defined Contribution pension while keeping it invested. You choose how much to withdraw and when, but you bear the risk of your pot running out.</dd>
              <dd><a href="/learn/what-is-drawdown" class="glossary-term__link">What is drawdown?</a></dd>
            </div>
          </dl>
        </div>

        <!-- E -->
        <div id="letter-E" class="glossary-letter-group">
          <div class="glossary-letter-heading">
            <span class="glossary-letter-heading__text" aria-hidden="true">E</span>
          </div>
          <dl class="glossary-term-list">
            <div id="emergency-fund" class="glossary-term" role="article">
              <dt class="glossary-term__name">Emergency Fund</dt>
              <dd class="glossary-term__definition">Money set aside in an easy-access account to cover unexpected expenses or a loss of income. A common target is 3&ndash;6 months of essential living costs.</dd>
              <dd><a href="/learn/guide/starting-out" class="glossary-term__link">Starting out guide</a></dd>
            </div>
            <div id="estate" class="glossary-term" role="article">
              <dt class="glossary-term__name">Estate</dt>
              <dd class="glossary-term__definition">Everything you own at the time of your death &mdash; property, savings, investments, pensions, and personal possessions &mdash; minus any debts. Your estate is what Inheritance Tax is calculated on.</dd>
            </div>
          </dl>
        </div>

        <!-- F -->
        <div id="letter-F" class="glossary-letter-group">
          <div class="glossary-letter-heading">
            <span class="glossary-letter-heading__text" aria-hidden="true">F</span>
          </div>
          <dl class="glossary-term-list">
            <div id="financial-adviser" class="glossary-term" role="article">
              <dt class="glossary-term__name">Financial Adviser (Independent Financial Adviser)</dt>
              <dd class="glossary-term__definition">A qualified professional who gives personalised financial advice. An Independent Financial Adviser can recommend products from the whole market, unlike a restricted adviser who only covers certain providers.</dd>
            </div>
          </dl>
        </div>

        <!-- G -->
        <div id="letter-G" class="glossary-letter-group">
          <div class="glossary-letter-heading">
            <span class="glossary-letter-heading__text" aria-hidden="true">G</span>
          </div>
          <dl class="glossary-term-list">
            <div id="gift-allowance" class="glossary-term" role="article">
              <dt class="glossary-term__name">Gift Allowance (Annual Exemption)</dt>
              <dd class="glossary-term__definition">You can give away &pound;3,000 per tax year without it counting towards your estate for Inheritance Tax purposes. Small gifts of up to &pound;250 per person are also exempt.</dd>
            </div>
            <div id="gross-income" class="glossary-term" role="article">
              <dt class="glossary-term__name">Gross Income</dt>
              <dd class="glossary-term__definition">Your total income before any deductions such as tax, National Insurance, or pension contributions.</dd>
            </div>
          </dl>
        </div>

        <!-- H -->
        <div id="letter-H" class="glossary-letter-group">
          <div class="glossary-letter-heading">
            <span class="glossary-letter-heading__text" aria-hidden="true">H</span>
          </div>
          <dl class="glossary-term-list">
            <div id="higher-rate" class="glossary-term" role="article">
              <dt class="glossary-term__name">Higher Rate</dt>
              <dd class="glossary-term__definition">The 40% income tax band that applies to taxable income between &pound;50,271 and &pound;125,140 (2026/27). If you earn in this band, you get less Personal Savings Allowance and more benefit from pension tax relief.</dd>
            </div>
          </dl>
        </div>

        <!-- I -->
        <div id="letter-I" class="glossary-letter-group">
          <div class="glossary-letter-heading">
            <span class="glossary-letter-heading__text" aria-hidden="true">I</span>
          </div>
          <dl class="glossary-term-list">
            <div id="income-protection" class="glossary-term" role="article">
              <dt class="glossary-term__name">Income Protection</dt>
              <dd class="glossary-term__definition">Insurance that pays a regular income (typically 50&ndash;70% of your salary) if you cannot work due to illness or injury. Unlike critical illness cover, it pays out monthly until you recover, reach retirement, or the policy ends.</dd>
            </div>
            <div id="income-tax" class="glossary-term" role="article">
              <dt class="glossary-term__name">Income Tax</dt>
              <dd class="glossary-term__definition">Tax paid on your earnings above the Personal Allowance. The UK has progressive bands: basic rate (20%), higher rate (40%), and additional rate (45%).</dd>
            </div>
            <div id="isa" class="glossary-term" role="article">
              <dt class="glossary-term__name">Individual Savings Account (ISA)</dt>
              <dd class="glossary-term__definition">A tax-free wrapper for savings or investments. You can contribute up to &pound;20,000 per tax year across all ISA types, and you pay no tax on any interest, dividends, or capital gains earned inside it.</dd>
              <dd><a href="/learn/what-is-an-isa" class="glossary-term__link">What is an ISA?</a></dd>
            </div>
            <div id="inheritance-tax" class="glossary-term" role="article">
              <dt class="glossary-term__name">Inheritance Tax</dt>
              <dd class="glossary-term__definition">Tax charged at 40% on the value of your estate above the nil rate band (&pound;325,000). A residence nil rate band of &pound;175,000 can apply if you leave your home to direct descendants.</dd>
              <dd><a href="/features/iht-planning" class="glossary-term__link">Inheritance Tax planning</a></dd>
            </div>
          </dl>
        </div>

        <!-- L -->
        <div id="letter-L" class="glossary-letter-group">
          <div class="glossary-letter-heading">
            <span class="glossary-letter-heading__text" aria-hidden="true">L</span>
          </div>
          <dl class="glossary-term-list">
            <div id="lasting-power-of-attorney" class="glossary-term" role="article">
              <dt class="glossary-term__name">Lasting Power of Attorney</dt>
              <dd class="glossary-term__definition">A legal document that lets you appoint someone to make decisions on your behalf if you lose mental capacity. There are two types: one for finances and one for health and welfare.</dd>
            </div>
            <div id="lifetime-allowance" class="glossary-term" role="article">
              <dt class="glossary-term__name">Lifetime Allowance (Abolished)</dt>
              <dd class="glossary-term__definition">Previously a cap on the total amount you could hold in pensions without incurring a tax charge. It was abolished in April 2024, though some transitional protections remain.</dd>
            </div>
            <div id="lifetime-isa" class="glossary-term" role="article">
              <dt class="glossary-term__name">Lifetime ISA</dt>
              <dd class="glossary-term__definition">An ISA for those aged 18&ndash;39, designed for saving towards a first home or retirement. The government adds a 25% bonus on contributions up to &pound;4,000 per year. Withdrawals for purposes other than a first home or retirement incur a 25% penalty.</dd>
              <dd><a href="/learn/what-is-an-isa" class="glossary-term__link">Learn about ISAs</a></dd>
            </div>
            <div id="loan-to-value" class="glossary-term" role="article">
              <dt class="glossary-term__name">Loan to Value</dt>
              <dd class="glossary-term__definition">The size of your mortgage as a percentage of the property&rsquo;s value. A &pound;180,000 mortgage on a &pound;200,000 property is 90% loan to value. Lower loan to value usually means better mortgage rates.</dd>
            </div>
          </dl>
        </div>

        <!-- M -->
        <div id="letter-M" class="glossary-letter-group">
          <div class="glossary-letter-heading">
            <span class="glossary-letter-heading__text" aria-hidden="true">M</span>
          </div>
          <dl class="glossary-term-list">
            <div id="money-purchase-annual-allowance" class="glossary-term" role="article">
              <dt class="glossary-term__name">Money Purchase Annual Allowance</dt>
              <dd class="glossary-term__definition">A reduced pension annual allowance of &pound;10,000 that applies once you have flexibly accessed your Defined Contribution pension (e.g. through drawdown). This limits how much you can contribute going forward while still getting tax relief.</dd>
            </div>
          </dl>
        </div>

        <!-- N -->
        <div id="letter-N" class="glossary-letter-group">
          <div class="glossary-letter-heading">
            <span class="glossary-letter-heading__text" aria-hidden="true">N</span>
          </div>
          <dl class="glossary-term-list">
            <div id="national-insurance" class="glossary-term" role="article">
              <dt class="glossary-term__name">National Insurance</dt>
              <dd class="glossary-term__definition">A tax on earnings that funds the State Pension and other benefits. Employees pay 8% on earnings between &pound;12,570 and &pound;50,270, and 2% above that (2026/27 rates).</dd>
            </div>
            <div id="net-income" class="glossary-term" role="article">
              <dt class="glossary-term__name">Net Income</dt>
              <dd class="glossary-term__definition">Your income after all deductions &mdash; income tax, National Insurance, pension contributions, and student loan repayments. Also called take-home pay.</dd>
            </div>
            <div id="net-worth" class="glossary-term" role="article">
              <dt class="glossary-term__name">Net Worth</dt>
              <dd class="glossary-term__definition">The total value of everything you own (assets) minus everything you owe (liabilities). It is the single best measure of your overall financial health.</dd>
              <dd><a href="/features/net-worth-dashboard" class="glossary-term__link">Track your net worth</a></dd>
            </div>
            <div id="nil-rate-band" class="glossary-term" role="article">
              <dt class="glossary-term__name">Nil Rate Band</dt>
              <dd class="glossary-term__definition">The threshold below which no Inheritance Tax is charged on your estate. Currently &pound;325,000 per person, and it has been frozen at this level since 2009.</dd>
              <dd><a href="/features/iht-planning" class="glossary-term__link">Inheritance Tax planning</a></dd>
            </div>
          </dl>
        </div>

        <!-- P -->
        <div id="letter-P" class="glossary-letter-group">
          <div class="glossary-letter-heading">
            <span class="glossary-letter-heading__text" aria-hidden="true">P</span>
          </div>
          <dl class="glossary-term-list">
            <div id="pension-annual-allowance" class="glossary-term" role="article">
              <dt class="glossary-term__name">Pension Annual Allowance</dt>
              <dd class="glossary-term__definition">The maximum total pension contributions (from you, your employer, and any third party) that qualify for tax relief in a single tax year. Currently &pound;60,000, reduced for those earning over &pound;260,000.</dd>
            </div>
            <div id="personal-allowance" class="glossary-term" role="article">
              <dt class="glossary-term__name">Personal Allowance</dt>
              <dd class="glossary-term__definition">The amount of income you can earn each year before paying income tax. Currently &pound;12,570, though it reduces by &pound;1 for every &pound;2 earned above &pound;100,000.</dd>
            </div>
            <div id="personal-savings-allowance" class="glossary-term" role="article">
              <dt class="glossary-term__name">Personal Savings Allowance</dt>
              <dd class="glossary-term__definition">The amount of savings interest you can earn tax-free outside of an ISA. &pound;1,000 for basic rate taxpayers, &pound;500 for higher rate, and &pound;0 for additional rate.</dd>
            </div>
          </dl>
        </div>

        <!-- R -->
        <div id="letter-R" class="glossary-letter-group">
          <div class="glossary-letter-heading">
            <span class="glossary-letter-heading__text" aria-hidden="true">R</span>
          </div>
          <dl class="glossary-term-list">
            <div id="residence-nil-rate-band" class="glossary-term" role="article">
              <dt class="glossary-term__name">Residence Nil Rate Band</dt>
              <dd class="glossary-term__definition">An additional Inheritance Tax allowance of &pound;175,000 that applies when you leave your main home to direct descendants (children or grandchildren). Combined with the nil rate band, a couple can potentially pass on &pound;1,000,000 tax-free.</dd>
              <dd><a href="/features/iht-planning" class="glossary-term__link">Inheritance Tax planning</a></dd>
            </div>
          </dl>
        </div>

        <!-- S -->
        <div id="letter-S" class="glossary-letter-group">
          <div class="glossary-letter-heading">
            <span class="glossary-letter-heading__text" aria-hidden="true">S</span>
          </div>
          <dl class="glossary-term-list">
            <div id="salary-sacrifice" class="glossary-term" role="article">
              <dt class="glossary-term__name">Salary Sacrifice</dt>
              <dd class="glossary-term__definition">An arrangement where you give up part of your salary in exchange for a non-cash benefit, most commonly extra pension contributions. You save on income tax and National Insurance, and your employer saves on National Insurance too.</dd>
            </div>
            <div id="sipp" class="glossary-term" role="article">
              <dt class="glossary-term__name">Self-Invested Personal Pension (SIPP)</dt>
              <dd class="glossary-term__definition">A personal pension that gives you full control over how your money is invested. You choose from a wide range of funds, shares, and other investments rather than being limited to your employer&rsquo;s default options.</dd>
              <dd><a href="/learn/should-i-consolidate-pensions" class="glossary-term__link">Should I consolidate pensions?</a></dd>
            </div>
            <div id="sequence-of-returns-risk" class="glossary-term" role="article">
              <dt class="glossary-term__name">Sequence of Returns Risk</dt>
              <dd class="glossary-term__definition">The risk that poor investment returns early in retirement permanently reduce the amount your pot can sustain, even if returns recover later. This is the biggest risk for anyone in drawdown.</dd>
              <dd><a href="/learn/what-is-drawdown" class="glossary-term__link">What is drawdown?</a></dd>
            </div>
            <div id="state-pension" class="glossary-term" role="article">
              <dt class="glossary-term__name">State Pension</dt>
              <dd class="glossary-term__definition">A regular payment from the government in retirement, based on your National Insurance record. The full new State Pension is &pound;221.20 per week (2026/27). You need 35 qualifying years for the full amount.</dd>
            </div>
            <div id="stocks-and-shares-isa" class="glossary-term" role="article">
              <dt class="glossary-term__name">Stocks and Shares ISA</dt>
              <dd class="glossary-term__definition">An ISA that lets you invest in funds, shares, bonds, and other assets with no tax on gains, dividends, or interest. Best suited for goals that are at least 5 years away.</dd>
              <dd><a href="/learn/what-is-an-isa" class="glossary-term__link">Learn about ISAs</a></dd>
            </div>
            <div id="student-loan" class="glossary-term" role="article">
              <dt class="glossary-term__name">Student Loan</dt>
              <dd class="glossary-term__definition">A government loan for tuition fees and maintenance. Repayments are income-contingent (you only pay above a salary threshold) and the balance is written off after 25&ndash;40 years depending on your plan type.</dd>
              <dd><a href="/calculators?calc=student-loan" class="glossary-term__link">Student loan calculator</a></dd>
            </div>
          </dl>
        </div>

        <!-- T -->
        <div id="letter-T" class="glossary-letter-group">
          <div class="glossary-letter-heading">
            <span class="glossary-letter-heading__text" aria-hidden="true">T</span>
          </div>
          <dl class="glossary-term-list">
            <div id="taper-relief" class="glossary-term" role="article">
              <dt class="glossary-term__name">Taper Relief</dt>
              <dd class="glossary-term__definition">A mechanism that reduces certain tax allowances as your income rises. For pensions, the annual allowance is reduced by &pound;1 for every &pound;2 of adjusted income above &pound;260,000, down to a minimum of &pound;10,000.</dd>
            </div>
            <div id="tax-free-cash" class="glossary-term" role="article">
              <dt class="glossary-term__name">Tax-Free Cash</dt>
              <dd class="glossary-term__definition">The portion of your pension you can take as a tax-free lump sum when you access it. For most people this is 25% of the pot, though some older pensions offer a higher percentage.</dd>
              <dd><a href="/learn/what-is-drawdown" class="glossary-term__link">What is drawdown?</a></dd>
            </div>
            <div id="tax-year" class="glossary-term" role="article">
              <dt class="glossary-term__name">Tax Year</dt>
              <dd class="glossary-term__definition">The UK tax year runs from 6 April to 5 April. Most tax allowances (ISA, pension, Capital Gains Tax) reset at the start of each tax year.</dd>
            </div>
          </dl>
        </div>

