    <section id="article" class="article-body" aria-labelledby="hero-heading">
      <div class="article-body__inner">
        <article class="article-card">

          <!-- The Short Answer -->
          <div class="article-section">
            <div class="article-highlight">
              <h2 class="article-highlight__heading">The Short Answer</h2>
              <p class="article-highlight__text">
                Drawdown (or flexi-access drawdown) lets you keep your pension invested while taking income from it.
                You choose how much to withdraw and when &mdash; giving you full control over your retirement income.
              </p>
            </div>
          </div>

          <!-- How It Works -->
          <div class="article-section">
            <h2 class="article-heading">How It Works</h2>
            <p class="article-body-text" style="margin-bottom:0.75rem;">
              At 55 (rising to 57 in 2028), you can access your Defined Contribution pension. The typical approach is:
            </p>
            <ol class="article-steps" aria-label="Drawdown steps">
              <li class="article-steps__item">Take up to <strong>25% tax-free</strong> as a lump sum.</li>
              <li class="article-steps__item">Move the remaining pot into drawdown.</li>
              <li class="article-steps__item">Draw income as you need it &mdash; monthly, annually, or ad hoc.</li>
              <li class="article-steps__item">The remaining pot stays invested and can continue to grow (or shrink).</li>
            </ol>
          </div>

          <!-- Drawdown vs Annuity -->
          <div class="article-section">
            <h2 class="article-heading">Drawdown vs Annuity</h2>
            <div class="article-compare-grid">
              <div class="article-compare-col">
                <p class="article-compare-col__heading">Drawdown</p>
                <ul class="article-compare-col__list" aria-label="Drawdown characteristics">
                  <li class="article-compare-col__list-item">Flexible &mdash; withdraw what you need</li>
                  <li class="article-compare-col__list-item">Pot can keep growing</li>
                  <li class="article-compare-col__list-item">You bear the investment risk</li>
                  <li class="article-compare-col__list-item">Remaining pot passes to beneficiaries</li>
                </ul>
              </div>
              <div class="article-compare-col">
                <p class="article-compare-col__heading">Annuity</p>
                <ul class="article-compare-col__list" aria-label="Annuity characteristics">
                  <li class="article-compare-col__list-item">Guaranteed income for life</li>
                  <li class="article-compare-col__list-item">No investment decisions to make</li>
                  <li class="article-compare-col__list-item">Inflexible once purchased</li>
                  <li class="article-compare-col__list-item">Rates may be poor at the time you buy</li>
                </ul>
              </div>
            </div>
          </div>

          <!-- The Risks -->
          <div class="article-section">
            <h2 class="article-heading">The Risks</h2>
            <ul class="article-list" aria-label="Drawdown risks">
              <li class="article-list__item">
                <span class="article-list__dot article-list__dot--raspberry" aria-hidden="true"></span>
                <span><strong>Sequence of returns risk.</strong> Poor investment returns in your early retirement years can devastate your pot &mdash; even if markets recover later.</span>
              </li>
              <li class="article-list__item">
                <span class="article-list__dot article-list__dot--raspberry" aria-hidden="true"></span>
                <span><strong>Longevity risk.</strong> Living longer than expected means your money needs to last longer.</span>
              </li>
              <li class="article-list__item">
                <span class="article-list__dot article-list__dot--raspberry" aria-hidden="true"></span>
                <span><strong>Taking too much too soon.</strong> Large early withdrawals reduce the pot that is left to grow.</span>
              </li>
            </ul>
          </div>

          <!-- Tax on Drawdown -->
          <div class="article-section">
            <h2 class="article-heading">Tax on Drawdown</h2>
            <p class="article-body-text">
              Withdrawals above the 25% tax-free amount are taxed as income. Taking large lump sums can push you into
              higher tax bands, so many people spread their withdrawals across multiple tax years to stay within lower bands.
            </p>
          </div>

