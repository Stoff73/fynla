          <!-- The Short Answer -->
          <div class="guide-highlight">
            <h2 class="guide-highlight__heading">The Short Answer</h2>
            <p class="guide-highlight__text">
              A Lasting Power of Attorney (LPA) is a legal document that lets you appoint someone you trust to make
              decisions on your behalf if you lose mental capacity. There are two types: one for finances, one for
              health and welfare.
            </p>
          </div>

          <!-- The Two Types -->
          <div class="guide-section">
            <h2 class="guide-section__heading">The Two Types</h2>
            <div class="guide-grid guide-grid--2">
              <div class="guide-card">
                <p class="guide-card__title">Property and Financial Affairs</p>
                <p class="guide-card__text">Covers bank accounts, bills, property, investments, and tax.</p>
                <p class="guide-card__text">Can be used while you still have capacity &mdash; useful if you are travelling or unwell.</p>
              </div>
              <div class="guide-card">
                <p class="guide-card__title">Health and Welfare</p>
                <p class="guide-card__text">Covers medical treatment, care, daily routine, and life-sustaining treatment.</p>
                <p class="guide-card__text">Can only be used when you lack capacity.</p>
              </div>
            </div>
          </div>

          <!-- Why You Need One -->
          <div class="guide-section">
            <h2 class="guide-section__heading">Why You Need One</h2>
            <p class="guide-section__lead">
              Without an LPA, your family would need to apply to the Court of Protection to manage your finances &mdash;
              a slow, expensive process that takes months, not days.
            </p>
            <div class="guide-grid guide-grid--2">
              <div class="guide-card">
                <p class="guide-card__label guide-card__label--spring">Lasting Power of Attorney</p>
                <ul class="guide-list guide-list--plain">
                  <li>Around &pound;82 to register</li>
                  <li>Takes 8&ndash;10 weeks to process</li>
                  <li>You choose who acts for you</li>
                </ul>
              </div>
              <div class="guide-card">
                <p class="guide-card__label guide-card__label--raspberry">Court of Protection</p>
                <ul class="guide-list guide-list--plain">
                  <li>&pound;400+ in fees</li>
                  <li>Much longer to arrange</li>
                  <li>The court decides who manages your affairs</li>
                </ul>
              </div>
            </div>
          </div>

          <!-- Who Should Be Your Attorney? -->
          <div class="guide-section">
            <h2 class="guide-section__heading">Who Should Be Your Attorney?</h2>
            <ul class="guide-bullet-list">
              <li class="guide-bullet-list__item">
                <span class="guide-bullet guide-bullet--spring" aria-hidden="true"></span>
                <span>Someone you trust completely.</span>
              </li>
              <li class="guide-bullet-list__item">
                <span class="guide-bullet guide-bullet--spring" aria-hidden="true"></span>
                <span>They must be over 18 and have mental capacity.</span>
              </li>
              <li class="guide-bullet-list__item">
                <span class="guide-bullet guide-bullet--spring" aria-hidden="true"></span>
                <span>You can appoint more than one person (jointly or jointly and severally).</span>
              </li>
              <li class="guide-bullet-list__item">
                <span class="guide-bullet guide-bullet--spring" aria-hidden="true"></span>
                <span>Consider: spouse, adult child, trusted friend, or a professional such as a solicitor.</span>
              </li>
            </ul>
          </div>

          <!-- Common Misconceptions -->
          <div class="guide-section">
            <h2 class="guide-section__heading">Common Misconceptions</h2>
            <ul class="guide-bullet-list">
              <li class="guide-bullet-list__item">
                <span class="guide-bullet guide-bullet--violet" aria-hidden="true"></span>
                <span><strong>&ldquo;I&rsquo;m too young.&rdquo;</strong> Accidents and illness do not check your age.</span>
              </li>
              <li class="guide-bullet-list__item">
                <span class="guide-bullet guide-bullet--violet" aria-hidden="true"></span>
                <span><strong>&ldquo;My spouse can do everything anyway.&rdquo;</strong> They cannot access your sole accounts or sell jointly-owned property without an LPA.</span>
              </li>
              <li class="guide-bullet-list__item">
                <span class="guide-bullet guide-bullet--violet" aria-hidden="true"></span>
                <span><strong>&ldquo;A will covers this.&rdquo;</strong> A will only takes effect after death, not during incapacity.</span>
              </li>
            </ul>
          </div>

